/**
 * SVG markup for an icon (one <path> per colour, run-length rows).
 * @param {string} name
 */
export function iconSvg(name) {
    const rows = MENU_ICONS[name] || MENU_ICONS.app;
    const paths = { '#': '', o: '', x: '' };
    rows.forEach((row, y) => {
        let x = 0;
        while (x < row.length) {
            const c = row[x];
            let run = 1;
            while (x + run < row.length && row[x + run] === c) {
                run++;
            }
            if (paths[c] !== undefined) {
                paths[c] += `M${x} ${y}h${run}v1h-${run}z`;
            }
            x += run;
        }
    });
    return `<svg class="pp-mi-svg" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">
        <path class="pp-mi-b" d="${paths['#']}"/><path class="pp-mi-a" d="${paths.o}"/><path class="pp-mi-x" d="${paths.x}"/>
    </svg>`;
}
